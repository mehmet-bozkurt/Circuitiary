  expect(await readoutNumber(page.getByTestId('circuit-min'))).toBeCloseTo(.35, 2)
  expect(await readoutNumber(page.getByTestId('circuit-max'))).toBeCloseTo(.35, 2)
  expect(await readoutNumber(page.getByTestId('circuit-delta'))).toBeCloseTo(0, 2)
  await stimulus.fill('0')
  await ablated.uncheck()
  expect(await readoutNumber(page.getByTestId('circuit-min'))).toBeCloseTo(.35, 2)
