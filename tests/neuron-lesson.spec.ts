  const stimulus = page.locator('#lesson-circuit-stimulus')
  const inhibitory = page.locator('#lesson-circuit-inhibitory')
  const ablated = page.locator('#lesson-circuit-ablated')
  await stimulus.fill('0.8')
  await inhibitory.uncheck()
  await ablated.uncheck()
  const excitatoryMaximum = await readoutNumber(page.getByTestId('circuit-max'))
  const paths = page.locator('#lesson-circuit').getByRole('img', { name: /Üç hücrenin boyutsuz aktivitesi/ }).locator('path')
  await expect(paths).toHaveCount(3)
  const excitatoryPaths = await paths.evaluateAll(elements => elements.map(path => path.getAttribute('d')))
  await inhibitory.check()
  const inhibitoryMaximum = await readoutNumber(page.getByTestId('circuit-max'))
  const inhibitoryMinimum = await readoutNumber(page.getByTestId('circuit-min'))
  expect(inhibitoryMinimum).toBeLessThan(.35)
  expect(inhibitoryMaximum).toBeLessThan(excitatoryMaximum)
  const inhibitoryPaths = await paths.evaluateAll(elements => elements.map(path => path.getAttribute('d')))
  expect(inhibitoryPaths.slice(0, 2)).toEqual(excitatoryPaths.slice(0, 2))
