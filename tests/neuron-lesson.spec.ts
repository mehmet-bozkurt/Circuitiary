const browserErrors = new WeakMap<Page, string[]>()

test.beforeEach(async ({ page }) => {
  const errors: string[] = []
  browserErrors.set(page, errors)
  const attached = new WeakSet<Page>()
  const attach = (target: Page) => {
    if (attached.has(target)) return
    attached.add(target)
    target.on('pageerror', error => errors.push(error.message))
    target.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  }
  attach(page)
  page.context().on('page', attach)
})

test.afterEach(async ({ page }) => {
  expect(browserErrors.get(page) ?? [], 'No browser exceptions or error-level console messages in any lesson scenario').toEqual([])
})

async function exported(page: Page) {
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: /Deney kaydını indir/ }).click()
  const download = await pending
  const path = await download.path()
  expect(path).not.toBeNull()
  return JSON.parse(await readFile(path!, 'utf8'))
}

async function expectNoHorizontalOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
}

async function readoutNumber(locator: Locator) {
  const text = (await locator.textContent())?.trim() ?? ''
  const token = text.match(/[-+]?\d+(?:[.,]\d+)?/)?.[0]
  const value = token ? Number(token.replace(',', '.')) : Number.NaN
  expect(Number.isFinite(value), `A finite numeric readout is required: ${text}`).toBe(true)
  return value
}

