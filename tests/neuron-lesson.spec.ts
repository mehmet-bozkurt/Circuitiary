test('lesson navigation supports touch and native desktop modified and middle clicks', async ({ page, isMobile }) => {
  await page.goto('/')
  const url = page.url()
  await expect(lessonLink(page)).toHaveAttribute('href', lessonPath)
  await expect(lessonLink(page)).not.toHaveAttribute('role', 'button')
  if (isMobile) {
    await lessonLink(page).tap()
    await expectLesson(page)
    await experimentLink(page).tap()
    await expect(page).toHaveURL(url)
    return
  }
  // Native browser link tabs can omit an opener relationship. The recorded
  // Chrome trace reports BrowserContext.page for the genuine modified click,
  // while Page.popup requires an opener. Observe the tab, then keep the same
  // exact lesson and unchanged source-page assertions for both native actions.
  const context = page.context()
  expect(context.pages()).toHaveLength(1)
  const modifierTab = context.waitForEvent('page')
  await lessonLink(page).click({ modifiers: ['ControlOrMeta'] })
  const modified = await modifierTab
  expect(modified).not.toBe(page)
  expect(context.pages()).toHaveLength(2)
  await expectLesson(modified)
  await expect(page).toHaveURL(url)
  await modified.close()
  expect(context.pages()).toHaveLength(1)
  const middleTab = context.waitForEvent('page')
  await lessonLink(page).click({ button: 'middle' })
  const middle = await middleTab
  expect(middle).not.toBe(page)
  expect(context.pages()).toHaveLength(2)
  await expectLesson(middle)
  await expect(page).toHaveURL(url)
  await middle.close()
  expect(context.pages()).toHaveLength(1)
})

